export const ARABIC_MONTHS = ["يناير", "فبراير", "مارس", "أبريل", "مايو", "يونيو", "يوليو", "أغسطس", "سبتمبر", "أكتوبر", "نوفمبر", "ديسمبر"];

export function translate(locale: AppLocale, text: string) {
  return locale === "ar" ? AR[text] || text : text;
}

export function monthLabel(locale: AppLocale, month: number) {
  const english = ["January", "February", "March", "April", "May", "June", "July", "August", "September", "October", "November", "December"];
  return locale === "ar" ? ARABIC_MONTHS[month] : english[month];
}

export function dateLocale(locale: AppLocale) {
  return locale === "ar" ? "ar-AE-u-nu-latn" : "en-GB";
}
